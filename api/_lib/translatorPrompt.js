export function extractReferencePerson(answers) {
  const q = answers.find(a => a?.question?.includes('닮고 싶은'));
  if (!q) return null;
  const val = (q.answer || (Array.isArray(q.selected) ? q.selected[0] : '')) + '';
  if (!val || /없|미입력|딱히/.test(val) || !val.trim()) return null;
  return val.trim();
}

// 스타일 성향 힌트 (에디토리얼 검색어에 사용)
export function extractStyleHint(answers) {
  const q = answers.find(a => a?.question?.includes('끌리') || a?.question?.includes('스타일'));
  if (!q) return '';
  const val = Array.isArray(q.selected) ? q.selected.join(' ') : (q.answer || '');
  return String(val || '').slice(0, 40);
}

export function buildAnswerText(answers = []) {
  if (!Array.isArray(answers)) return "";
  return answers
    .map((a) => {
      if (!a?.question) return null;
      const parts = [];
      if (a.answer && String(a.answer).trim()) parts.push(a.answer);
      if (Array.isArray(a.selected) && a.selected.length) parts.push(a.selected.join(", "));
      if (a.other && String(a.other).trim()) parts.push(`기타: ${a.other}`);
      const val = parts.join(" / ") || "(미입력)";
      return `Q. ${a.question.replace(/\n/g, " ")}\n→ ${val}`;
    })
    .filter(Boolean)
    .join("\n\n");
}

